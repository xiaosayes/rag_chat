/**
 * web-046：前端展示层 Markdown 清洗——答案气泡展示前剥离 Markdown 语法符号
 *（** 粗体 / * 斜体 / 标题 / 引用 / 列表符 / 链接 / 图片 / 表格 / 删除线 / 行内代码）。
 *
 * 设计约束（用户拍板）：不误伤正确且必要的符号——小数（2.2号馆）、日期/区间
 *（3月18日—21日、3~5）、百分比、货币、有序列表序号（展示保留可读性）、乘法式（3*5）；
 * 剥离标记后压缩连续空白，保证文本可展示性、可读性与连续性。
 * 原始流式文本不改动（重播缓存/日志均为原文），仅在渲染时清洗（天然处理跨 chunk 的 **）。
 */

/** 答案文本 → 展示文本（幂等；空输入返回空串） */
export function cleanForDisplay(text: string): string {
  if (!text) return "";
  let t = text.replace(/\r\n?/g, "\n");

  // 代码块：去围栏保留内容
  t = t.replace(/```([\s\S]*?)```/g, (_m, inner: string) => inner);
  // 图片/链接语法 → 保留文字
  t = t.replace(/!\[([^\]]*)\]\([^)]*\)/g, "$1");
  t = t.replace(/\[([^\]]+)\]\([^)]*\)/g, "$1");
  // HTML 标签 → 保留内文
  t = t.replace(/<\/?[a-zA-Z][^>]*>/g, "");
  // 表格分隔行整行删除
  t = t.replace(/^\s*\|?[\s|:]+-{2,}[\s|:-]*\|?\s*$/gm, "");

  // 行级规则
  t = t
    .split("\n")
    .map((line) => {
      line = line.replace(/^\s*#{1,6}\s+/, ""); // 标题标记
      line = line.replace(/^\s*>\s?/, ""); // 引用标记
      line = line.replace(/^\s*[-*+]\s+/, ""); // 无序列表符
      if (/^\s*\|.*\|\s*$/.test(line)) {
        // 表格行：去首尾竖线，单元格以「，」相连（可读性）
        line = line
          .replace(/^\s*\|/, "")
          .replace(/\|\s*$/, "")
          .split("|")
          .map((c) => c.trim())
          .join("，");
      }
      return line;
    })
    .join("\n");

  // 行内代码反引号 → 保留内容
  t = t.replace(/`([^`\n]+)`/g, "$1");
  // 删除线 / 下划线粗体 → 保留内容
  t = t.replace(/~~([^~]+)~~/g, "$1");
  t = t.replace(/__([^_]+)__/g, "$1");
  // ** 粗体：成对或未配对一律剥除（流式切段常造成未配对）
  t = t.replace(/\*\*/g, "");
  // 单 * 斜体：仅当成对包裹文字时剥离（*斜体*）；面积 3*5 等乘法式不受影响
  t = t.replace(/\*([^*\s][^*\n]*?)\*/g, "$1");

  // 连续性：压缩连续空白（保留换行）、中文标点前不留空格
  t = t.replace(/[ \t]{2,}/g, " ");
  t = t.replace(/[ \t]+([，。！？；：、）】》…—])/g, "$1");
  return t;
}
